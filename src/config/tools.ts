const byId = new Map(tools.map((t) => [t.id, t]));

export function getTool(id: ToolId): ToolDefinition {
  const tool = byId.get(id);
  if (!tool) throw new Error(`Unknown tool: ${id}`);
  return tool;
}

export function isToolId(value: string): value is ToolId {
  return byId.has(value as ToolId);
}

export function findToolBySlug(locale: Locale, slug: string): ToolDefinition | undefined {
  return tools.find((t) => t.slugs[locale] === slug);
}

/** Tool that opens a given detected data kind, if any. */
export function toolForKind(kind: DataKind): ToolId | undefined {
  return tools.find((t) => t.detects.includes(kind))?.id;
}

/** Tools grouped by menu block, preserving registry order. */
export function groupedTools(): ToolDefinition[][] {
  const groups = new Map<number, ToolDefinition[]>();
  for (const tool of tools) {
    const list = groups.get(tool.group) ?? [];
    list.push(tool);
    groups.set(tool.group, list);
  }
  return [...groups.entries()].sort(([a], [b]) => a - b).map(([, list]) => list);
}
