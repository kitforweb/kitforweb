export interface ToolDefinition {
  id: ToolId;
  group: number; // menu block (separator)
  icon: LucideIcon;
  slugs: Record<Locale, string>; // slug per locale
  keywords: string[]; // search and Ctrl+K
  sensitive: boolean; // no persistence or share link
  shareable: boolean; // content stored in the URL hash
  detects: DataKind[]; // smart-detector data kinds that open this tool
  messages?: string[]; // shared message namespaces it needs on the client (e.g. "regex")
  load: () => Promise<{ default: ComponentType }>;
}

